        )
    OUTPUT S.GroupID, inserted.IDPosizioneTTOO
    INTO #Mappa(GroupID, IDPosizioneTTOO);

    INSERT INTO dbo.TTOO_Posizioni_FFAA(IDPosizioneTTOO, id_arma)
    SELECT m.IDPosizioneTTOO, f.id_arma
    FROM #AtteseFFAA f
    INNER JOIN #Mappa m ON m.GroupID = f.GroupID;

    COMMIT TRANSACTION;

    SELECT
        COUNT(*) AS PosizioniInserite,
        SUM(NumeroPrevisto) AS UnitaPreviste
    FROM dbo.TTOO_Posizioni;

    SELECT COUNT(*) AS AssociazioniFFAA
    FROM dbo.TTOO_Posizioni_FFAA;
