    (
        GroupID int NOT NULL PRIMARY KEY,
        IDPosizioneTTOO int NOT NULL UNIQUE
    );

    MERGE dbo.TTOO_Posizioni AS D
    USING #Attese AS S
       ON 1 = 0
    WHEN NOT MATCHED THEN
        INSERT
        (
            ID_Uff1, ID_Uff2, ID_Uff3, id_tipo_incarico,
            TipoPersonale, ID_CategoriaMilitare, ID_Titolo_Previsto,
            NumeroPrevisto, Attivo, Note
        )
        VALUES
        (
            S.ID_Uff1, S.ID_Uff2, S.ID_Uff3, S.id_tipo_incarico,
            S.TipoPersonale, S.ID_CategoriaMilitare, S.ID_Titolo_Previsto,
